"""Write myst.yml (site config + table of contents).  Run from book/.

--partial  include only files that already exist (for trial builds).
"""
import json
import pathlib
import sys

BOOK = pathlib.Path(__file__).resolve().parents[1]
partial = "--partial" in sys.argv

LABS = ["01-chance", "02-bayes", "03-causal-inference", "04-interference", "05-qubit-bloch",
        "06-entanglement-bell", "07-noise-channels", "08-variational-gradients", "09-quantum-switch",
        "10-classical-shadows", "11-quantum-causal-inference"]


def ok(f: str) -> bool:
    return (not partial) or (BOOK / f).exists()


def entry(f, ind, children=None, title=None):
    if not ok(f):
        return []
    out = [" " * ind + f"- file: {f}"]
    if title:
        out.append(" " * ind + f"  title: {json.dumps(title)}")
    if children:
        out.append(" " * ind + "  children:")
        for c in children:
            out += entry(c, ind + 4)
    return out


toc_levels = json.loads((BOOK / "_data" / "toc-levels.json").read_text(encoding="utf-8"))
lines = []
lines += entry("index.ipynb", 4)
lines += ["    - title: Start here", "      children:"]
for f in ["start/how-to-use.md", "start/roadmap.ipynb", "start/setup.md"]:
    lines += entry(f, 8)
lines += ["    - title: Course levels", "      children:"]
for lv in toc_levels:
    lines += entry(lv["file"], 8, [c["file"] for c in lv["children"]])
lines += entry("labs/index.md", 4, [f"labs/{n}.ipynb" for n in LABS])
lines += entry("media/watch-listen.md", 4)
lines += ["    - title: Reference", "      children:"]
for f in ["reference/glossary.md", "reference/bibliography.md",
          "reference/about.md"]:
    lines += entry(f, 8)

cfg = f"""# Generated by scripts/make_config.py — edit that script, not this file.
version: 1
project:
  id: quantum-causal-ai
  title: Quantum Causal AI
  subtitle: An open, interactive course from counting to research frontiers
  description: A free, interactive Jupyter Book that teaches quantum causal AI from first principles - counting, chance and causal graphs through quantum information, quantum causal models, indefinite causal order and quantum machine learning - with verified references, videos and runnable labs.
  keywords: [quantum causal models, causal inference, quantum information, quantum machine learning, indefinite causal order, Jupyter Book]
  authors:
    - name: Amir Rafe
      url: https://pozapas.github.io/
      github: pozapas
  github: https://github.com/pozapas/quantum-causal-ai
  license:
    content: CC-BY-4.0
    code: MIT
  bibliography: [references.bib]
  jupyter:
    binder:
      repo: pozapas/quantum-causal-ai
      ref: main
  exclude: [_build/**, evidence/**, deploy/**, scripts/**, tests/**, qcai/**, README.md, "_data/**"]
  toc:
{chr(10).join(lines)}
site:
  template: book-theme
  title: Quantum Causal AI
  options:
    logo: _static/logo.svg
    logo_dark: _static/logo-dark.svg
    favicon: _static/favicon.svg
    style: _static/qcai.css
    folders: true
    logo_alt: Quantum Causal AI logo
    hide_authors: true
    hide_footer_links: true
  nav:
    - title: Start
      url: /levels/level-0
    - title: Labs
      url: /labs
    - title: Watch and listen
      url: /media/watch-listen
  actions:
    - title: Author site
      url: https://pozapas.github.io/
"""
(BOOK / "myst.yml").write_text(cfg, encoding="utf-8")
print("myst.yml written", "(partial)" if partial else "")
